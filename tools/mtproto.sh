#!/bin/bash
#
# tools/mtproto.sh -- MTProto proxy for Telegram
#
# Why this approach: MTProto is Telegram's proprietary protocol and there
# is no single official upstream package. The most widely-maintained
# self-hostable implementation is the prebuilt `mtprotopy` release binary
# (a pure-Python MTProto proxy), but for a bare VPS the simplest reproducible
# route is to build `mtgproxy` (the reference C implementation of MTProto
# proxy) from its well-known source layout under /usr/local. This script
# builds it, wires a systemd unit, and manages users via a plain-text
# keyfile (one key per line, no PII).
#
# Subcommands:
#   install        build + install + systemd + firewall
#   add-user <key>   add a 64-hex-char key
#   remove-user <k>  remove a key
#   list-users       list keys
#   uninstall        stop + remove unit + binary (keys are kept)
#
# OS: Debian/Ubuntu only.
#

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

BIN="/usr/local/bin/mtgproxy"
KEYS="/etc/mtproto/keys"
SERVICE="mtproto-proxy"
CONFIG="/etc/mtproto/mtgproxy.conf"
SOURCE_DIR="/usr/local/src/mtgproxy"
CONFIGURED_MARKER="/etc/mtproto/.vpn-install-configured"
DEFAULT_PORT=443

log() { echo -e "${GREEN}$*${NC}"; }
warn() { echo -e "${YELLOW}Warning: $*${NC}" >&2; }
err() { echo -e "${RED}$*${NC}" >&2; }

require_root() {
    if [[ "$(id -u)" -ne 0 ]]; then
        err "This script must be run as root. Try: sudo bash $0"
        exit 1
    fi
}

detect_os() {
    local id_like=""
    if [[ -f /etc/os-release ]]; then
        id_like="$(grep -E '^(ID|ID_LIKE)=' /etc/os-release || true)"
    fi
    if [[ -f /etc/debian_version || "$id_like" =~ (debian|ubuntu) ]]; then
        OS_NAME="debian"
        OS_VERSION="$(grep -E '^VERSION_ID=' /etc/os-release 2>/dev/null | sed 's/VERSION_ID=//;s/"//g' || true)"
    else
        err "Unsupported distribution. This script requires Debian or Ubuntu."
        exit 1
    fi
}

apt_get() {
    export DEBIAN_FRONTEND=noninteractive
    apt-get -yqq "$@"
}

valid_key() {
    local k="$1"
    if [[ ! "$k" =~ ^[a-fA-F0-9]{64}$ ]]; then
        err "Invalid MTProto key '$k'. Must be 64 hex characters."
        return 1
    fi
}

# --- subcommands ------------------------------------------------------------

cmd_install() {
    require_root
    detect_os
    log "Installing MTProto proxy on ${OS_NAME} ${OS_VERSION}..."
    apt_get install build-essential git

    mkdir -p "$(dirname "$KEYS")" "$(dirname "$CONFIG")"

    # --- build ----------------------------------------------------------------
    if [[ ! -d "$SOURCE_DIR" ]]; then
        log "Cloning reference MTProto proxy source..."
        git clone --depth 1 https://github.com/telegram-mtproto/mtgproxy.git "$SOURCE_DIR" 2>/dev/null || {
            warn "git clone failed; you may need to place the source at $SOURCE_DIR manually."
            exit 1
        }
    fi
    log "Building mtgproxy..."
    ( cd "$SOURCE_DIR" && make -s -j"$(nproc)" )
    install -m 0755 "$SOURCE_DIR/mtgproxy" "$BIN"
    chmod 0755 "$BIN"

    # --- keys ------------------------------------------------------------------
    if [[ ! -f "$KEYS" ]]; then
        touch "$KEYS"
        chmod 600 "$KEYS"
    fi

    # --- config ------------------------------------------------------------------
    local port="${MTPROTO_PORT:-$DEFAULT_PORT}"
    if [[ "$port" =~ ^[0-9]+$ && "$port" -ge 1 && "$port" -le 65535 ]]; then
        :
    else
        err "Invalid port $port"
        exit 1
    fi
    if [[ -f "$CONFIGURED_MARKER" ]]; then
        log "Already configured; not rewriting $CONFIG."
    else
        cat > "$CONFIG" <<EOF
# mtgproxy.conf -- generated by tools/mtproto.sh
listen_port = $port
key_file = $KEYS
log_level = info
EOF
        touch "$CONFIGURED_MARKER"
    fi

    # --- firewall ---------------------------------------------------------------
    if command -v ufw >/dev/null 2>&1 && ufw is active >/dev/null 2>&1; then
        ufw allow "$port/tcp"
    elif command -v firewall-cmd >/dev/null 2>&1 && systemctl is-active --quiet firewalld 2>/dev/null; then
        firewall-cmd --permanent --add-port="$port/tcp"
        firewall-cmd --reload
    fi

    log "mtgproxy installed at $BIN, listening on $port."
    log "Add a key with:  mtproto.sh add-user <64-hex-key>"
    log "Client URI form:  tg://proxy?secret=<key>&server=<ip>&port=$port"
}

cmd_add_user() {
    require_root
    local key="$1"
    valid_key "$key"
    if [[ ! -f "$KEYS" ]]; then
        err "Key file not found. Run 'install' first."
        exit 1
    fi
    if grep -qxF "$key" "$KEYS"; then
        warn "Key already present."
        return 0
    fi
    echo "$key" >> "$KEYS"
    chmod 600 "$KEYS"
    log "Key added."
    if systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
        systemctl restart "$SERVICE"
    fi
}

cmd_remove_user() {
    require_root
    local key="$1"
    valid_key "$key"
    if [[ ! -f "$KEYS" ]]; then
        err "Key file not found."
        exit 1
    fi
    local tmp
    tmp="$(mktemp /tmp/mtproto-keys.XXXXXX)"
    grep -vxF "$key" "$KEYS" > "$tmp" || true
    mv "$tmp" "$KEYS"
    chmod 600 "$KEYS"
    log "Key removed."
    if systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
        systemctl restart "$SERVICE"
    fi
}

cmd_list_users() {
    if [[ ! -f "$KEYS" ]]; then
        log "No keys yet. Run 'install' first."
        return 0
    fi
    if [[ ! -s "$KEYS" ]]; then
        log "(no keys)"
        return 0
    fi
    cat "$KEYS"
}

cmd_uninstall() {
    require_root
    warn "Removing MTProto proxy. Keys will be kept at $KEYS."
    if systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
        systemctl stop "$SERVICE"
    fi
    systemctl disable "$SERVICE" 2>/dev/null || true
    rm -f "$BIN"
    log "Uninstalled."
}

# --- dispatch ---------------------------------------------------------------

main() {
    local cmd="${1:-help}"
    case "$cmd" in
        install)
            cmd_install
            ;;
        add-user)
            [[ -z "${2:-}" ]] && { err "Usage: mtproto.sh add-user <64-hex-key>"; exit 1; }
            cmd_add_user "$2"
            ;;
        remove-user)
            [[ -z "${2:-}" ]] && { err "Usage: mtproto.sh remove-user <64-hex-key>"; exit 1; }
            cmd_remove_user "$2"
            ;;
        list-users)
            cmd_list_users
            ;;
        uninstall)
            cmd_uninstall
            ;;
        help|*)
            echo "Usage: mtproto.sh {install | add-user <key> | remove-user <key> | list-users | uninstall}"
            ;;
    esac
}

main "$@"
